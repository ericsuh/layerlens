package gen

import (
	"fmt"
	"os"
	"path/filepath"
)

// Pairs returns every fixture pair, in a fixed order.
//
// One OCI layout directory per pair, rather than one layout for everything:
// each pair is then independently loadable (`--fixtures-dir` can point at a
// subset), the blob store of a pair shows the sharing between exactly the two
// images a reviewer is comparing, and a change to one pair cannot reshuffle
// another's index.json.
func Pairs() []PairSpec {
	return []PairSpec{
		examplePair(),
		prefixPair(),
		disjointPair(),
		edgecasePair(),
		widePair(),
	}
}

// Build writes every pair under root and returns their reports.
func Build(root string) ([]*PairReport, error) {
	if err := os.MkdirAll(root, 0o755); err != nil {
		return nil, err
	}
	pairs := Pairs()
	reports := make([]*PairReport, 0, len(pairs))
	for i := range pairs {
		r, err := WritePair(root, &pairs[i])
		if err != nil {
			return nil, fmt.Errorf("gen: pair %s: %w", pairs[i].Name, err)
		}
		reports = append(reports, r)
	}
	if err := writeGitattributes(root); err != nil {
		return nil, err
	}
	return reports, nil
}

// writeGitattributes marks the blob store binary so that git neither tries to
// diff a gzip stream nor rewrites line endings inside one. The vendored
// fixtures are only reviewable if `git diff` stays quiet about the blobs and
// loud about index.json.
func writeGitattributes(root string) error {
	const content = `# Generated by cmd/genfixtures. Layer, config and manifest blobs are
# content-addressed bytes: never diff them, never touch their line endings.
**/blobs/sha256/** binary
`
	return os.WriteFile(filepath.Join(root, ".gitattributes"), []byte(content), 0o644)
}
